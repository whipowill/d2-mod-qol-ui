"""Writes src/palette.h: the game's Act 1 palette (RGB), used to match the automap label colours to a cross's palette index.
usage: make_palette_h.py <game folder with d2data.mpq> <out palette.h>"""
import sys, os, importlib.util
sp = importlib.util.spec_from_file_location('mq', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'make_qol_ui_mpq.py'))
mq = importlib.util.module_from_spec(sp); sp.loader.exec_module(mq)
if len(sys.argv) != 3: sys.exit(__doc__)
raw = mq.MPQ(os.path.join(sys.argv[1], 'd2data.mpq')).read('data\\global\\palette\\ACT1\\Pal.dat')
rows = ['    {%d,%d,%d},' % (raw[i * 3 + 2], raw[i * 3 + 1], raw[i * 3]) for i in range(256)]   # the file is BGR
open(sys.argv[2], 'w').write('// Generated by tools/make_palette_h.py: the game\'s Act 1 palette as RGB.\n#ifndef UI_PALETTE_H\n#define UI_PALETTE_H\nstatic const unsigned char am_pal[256][3] = {\n' + '\n'.join(rows) + '\n};\n#endif\n')
